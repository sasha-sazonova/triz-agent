def main():
    data = yaml.safe_load(PATH.read_text(encoding="utf-8"))
    have = {p["id"] for p in data["principles"]}
    added = []
    for pid, (name, desc, subs, exs) in sorted(DATA.items()):
        if pid in have:
            continue
        data["principles"].append({
            "id": pid, "name": name, "description": desc,
            "sub_principles": list(subs), "examples": list(exs),
        })
        added.append(pid)
    # сортировка по id для читаемости
    data["principles"].sort(key=lambda p: p["id"])
    PATH.write_text(
        yaml.safe_dump(data, allow_unicode=True, sort_keys=False),
        encoding="utf-8")
    ids = [p["id"] for p in data["principles"]]
    print(f"added: {added}")
    print(f"total: {len(ids)}/40; missing: {[i for i in range(1,41) if i not in ids]}")

if __name__ == "__main__":
    main()
